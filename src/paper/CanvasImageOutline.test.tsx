import {act} from 'react';
import {createRoot} from 'react-dom/client';
import {afterEach,beforeEach,describe,expect,it,vi} from 'vitest';
import {CanvasImageOutline} from './CanvasImageOutline';
import type {PlacedImage} from '../schema/document';
beforeEach(()=>vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT',true));
afterEach(()=>vi.unstubAllGlobals());
const source:PlacedImage={id:'stroke',assetId:'a',widthCols:2,caption:'',anchor:{page:1,column:0,y:100}};
const asset={src:'data:image/png;base64,AA==',naturalWidth:800,naturalHeight:400};
describe('canvas outline drafting',()=>{
  it('draws a complete freehand border, with no point controls and one explicit apply',()=>{
    const host=document.createElement('div'),root=createRoot(host),apply=vi.fn();document.body.append(host);
    act(()=>root.render(<CanvasImageOutline image={source} asset={asset} onApply={apply} onCancel={()=>{}}/>));
    const svg=host.querySelector('svg')!;
    vi.spyOn(svg,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:200,height:200,right:200,bottom:200,x:0,y:0,toJSON(){}});
    const pointer=(type:string,x:number,y:number)=>{const event=new MouseEvent(type,{bubbles:true,button:0,clientX:x,clientY:y});Object.defineProperty(event,'pointerId',{value:1});svg.dispatchEvent(event);};
    act(()=>pointer('pointerdown',180,100));
    act(()=>{for(let i=1;i<=400;i++)pointer('pointermove',100+80*Math.cos(i/400*Math.PI*2),100+80*Math.sin(i/400*Math.PI*2));});
    act(()=>pointer('pointerup',180,100));
    expect(apply).not.toHaveBeenCalled();expect(svg.querySelectorAll('circle')).toHaveLength(0);
    expect(document.querySelector('[aria-label="Point X"]')).toBeNull();
    const button=(label:string)=>[...document.querySelectorAll<HTMLButtonElement>('.canvas-outline-tools button')].find(b=>b.textContent===label)!;
    act(()=>button('Apply border').click());
    expect(apply).toHaveBeenCalledTimes(1);const points=apply.mock.calls[0][0] as {x:number;y:number}[];
    expect(points.length).toBeLessThanOrEqual(128);
    expect(Math.min(...points.map(p=>p.x))).toBeLessThan(11);expect(Math.max(...points.map(p=>p.y))).toBeGreaterThan(89);
    expect(source.wrapPolygon).toBeUndefined();
    act(()=>button('Undo stroke').click());
    expect(host.querySelector('polygon')!.getAttribute('points')).toContain('0,0');
    act(()=>root.unmount());host.remove();
  });
  it('disables invalid outlines and cancels without applying',()=>{
    const host=document.createElement('div'),root=createRoot(host),apply=vi.fn(),cancel=vi.fn();document.body.append(host);
    act(()=>root.render(<CanvasImageOutline image={source} asset={asset} onApply={apply} onCancel={cancel}/>));
    const svg=host.querySelector('svg')!;
    const event=new MouseEvent('pointerdown',{bubbles:true,button:0,clientX:0,clientY:0});Object.defineProperty(event,'pointerId',{value:1});
    act(()=>svg.dispatchEvent(event));
    expect(document.querySelector<HTMLButtonElement>('.canvas-outline-apply')!.disabled).toBe(true);
    act(()=>window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'})));
    expect(cancel).toHaveBeenCalledTimes(1);expect(apply).not.toHaveBeenCalled();
    act(()=>root.unmount());host.remove();
  });
});
