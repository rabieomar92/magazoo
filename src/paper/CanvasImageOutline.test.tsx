import {act} from 'react';
import {createRoot} from 'react-dom/client';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {CanvasImageOutline} from './CanvasImageOutline';
beforeEach(()=>vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT',true));
afterEach(()=>vi.unstubAllGlobals());
it('edits polygon vertices without freehand drawing and applies only wrapping',()=>{
 const host=document.createElement('div');document.body.append(host);const root=createRoot(host),apply=vi.fn();
 const image={id:'a',assetId:'a',caption:'',widthCols:2 as const,anchor:{page:1,column:0,y:50}};
 act(()=>root.render(<CanvasImageOutline image={image} asset={{src:'',naturalWidth:100,naturalHeight:100}} onApply={apply} onCancel={()=>{}}/>));
 const svg=host.querySelector('svg')!;
 expect(svg.querySelectorAll('[data-vertex]')).toHaveLength(4);
 act(()=>svg.dispatchEvent(new MouseEvent('pointerdown',{bubbles:true,button:0})));
 expect(svg.querySelectorAll('[data-vertex]')).toHaveLength(4);
 act(()=>svg.querySelector('[data-vertex]')!.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true})));
 expect(svg.querySelector('.polygon-point-visible')!.getAttribute('cx')).toBe('4');
 expect(svg.querySelectorAll('ellipse')).toHaveLength(0);
 expect(svg.querySelector('.polygon-point-visible')!.tagName.toLowerCase()).toBe('circle');
 expect(svg.querySelector('.polygon-point-visible')!.getAttribute('r')).toBe('4');
 act(()=>svg.querySelector('[data-vertex]')!.dispatchEvent(new KeyboardEvent('keydown',{key:'Delete',bubbles:true})));
 expect(svg.querySelectorAll('[data-vertex]')).toHaveLength(3);
 act(()=>svg.querySelector('[data-vertex]')!.dispatchEvent(new KeyboardEvent('keydown',{key:'Delete',bubbles:true})));
 expect(svg.querySelectorAll('[data-vertex]')).toHaveLength(3);
 vi.spyOn(svg,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:100,height:100} as DOMRect);
 act(()=>svg.querySelector('line')!.dispatchEvent(new MouseEvent('click',{bubbles:true,clientX:100,clientY:50})));
 expect(svg.querySelectorAll('[data-vertex]')).toHaveLength(4);expect(apply).not.toHaveBeenCalled();
 act(()=>document.querySelector<HTMLButtonElement>('.canvas-outline-apply')!.click());
 expect(apply).toHaveBeenCalledTimes(1);expect(apply.mock.calls[0][1]).toBe(0);expect(image).not.toHaveProperty('frame');
 act(()=>root.unmount());host.remove();
});
